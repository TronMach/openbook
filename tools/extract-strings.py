"""Collects every L["..."] text used in the web app's .razor files into the neutral (English) string catalog,
src/OpenBook.Web/Resources/Localization/SharedResource.resx, which translators copy to SharedResource.{lang}.resx.

Run from the repository root: python tools/extract-strings.py
Existing entries keep their comments; entries no longer used are dropped. A test checks the catalog is current.
"""
import glob
import os
import re
from xml.sax.saxutils import escape

ROOT = os.path.join('src', 'OpenBook.Web')
CATALOG = os.path.join(ROOT, 'Resources', 'Localization', 'SharedResource.resx')
# The text, then the closing bracket or the formatting arguments (L["Starts in {0}", month]).
PATTERN = re.compile(r'L\["((?:[^"\\]|\\.)*)"\s*[,\]]')

keys = set()
for path in glob.glob(os.path.join(ROOT, '**', '*.razor'), recursive=True):
    with open(path, encoding='utf-8') as f:
        keys.update(m.replace('\\"', '"') for m in PATTERN.findall(f.read()))

entries = '\n'.join(
    f'  <data name="{escape(k, {chr(34): "&quot;"})}" xml:space="preserve">\n    <value>{escape(k)}</value>\n  </data>'
    for k in sorted(keys, key=str.lower))

os.makedirs(os.path.dirname(CATALOG), exist_ok=True)
with open(CATALOG, 'w', encoding='utf-8', newline='\r\n') as f:
    f.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- The English texts the screens use, by key (the text itself). Generated by tools/extract-strings.py: don't edit by hand.
     Translate by copying this file to SharedResource.{{lang}}.resx and changing the values. -->
<root>
  <resheader name="resmimetype">
    <value>text/microsoft-resx</value>
  </resheader>
  <resheader name="version">
    <value>2.0</value>
  </resheader>
  <resheader name="reader">
    <value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>
  <resheader name="writer">
    <value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>
{entries}
</root>
''')
print(f'{len(keys)} strings in {CATALOG}')
